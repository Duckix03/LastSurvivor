  // SVG do ícone: sombra (1 px) + pixels, tudo em retângulos (linhas juntadas pra ficar leve)
  svg(name) {
    if (this.cache[name]) return this.cache[name];
    const art = this.ART[name]; if (!art) return '';
    const rects = (shadow) => {
      let out = '';
      art.forEach((row, y) => {
        let x = 0;
        while (x < 16) {
          const ch = row[x];
          if (!ch || ch === '.') { x++; continue; }
          let w = 1; while (x + w < 16 && row[x + w] === ch) w++;
          const col = shadow ? 'rgba(0,0,0,0.5)' : (this.COLORS[ch] || '#fff');
          out += '<rect x="' + (x + (shadow ? 1 : 0)) + '" y="' + (y + (shadow ? 1 : 0)) + '" width="' + w + '" height="1" fill="' + col + '"/>';
          x += w;
        }
      });
      return out;
    };
    return (this.cache[name] = '<svg class="pix" viewBox="0 0 17 17" shape-rendering="crispEdges" aria-hidden="true">' + rects(true) + rects(false) + '</svg>');
  },
